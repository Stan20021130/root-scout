"""Repository check executor, result parser, and CI artifact integration for RootScout."""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import threading
import time
import uuid
import xml.etree.ElementTree as ET
from typing import Dict, List, Optional, Tuple, Any

# Standard Pytest exit code mappings per official documentation:
# 0: All tests were collected and passed
# 1: Tests were collected and run but some of the tests failed
# 2: Test execution was interrupted by the user
# 3: Internal error happened while executing tests
# 4: pytest command line usage error
# 5: No tests were collected
PYTEST_EXIT_CODES = {
    0: "passed",
    1: "assertion_failed",
    2: "interrupted",
    3: "internal_error",
    4: "usage_error",
    5: "no_tests_collected"
}


def classify_exit(tool: str, exit_code: int, timed_out: bool = False, stderr: str = "") -> str:
    """Accurately classify check outcome distinguishing assertion failures from env errors."""
    if timed_out:
        return "timeout"
    if exit_code == 0:
        return "passed"
    
    tool_lower = tool.lower()
    if "pytest" in tool_lower:
        return PYTEST_EXIT_CODES.get(exit_code, "failed")
    
    # Generic unittest / custom runner heuristic
    if exit_code == 1:
        # Standard Python unittest exits with 1 on test failures or syntax/import errors
        if "AssertionError" in stderr or "FAIL:" in stderr or "FAILED (" in stderr:
            return "assertion_failed"
        if "ImportError" in stderr or "ModuleNotFoundError" in stderr or "SyntaxError" in stderr:
            return "import_failed"
        return "failed"

    if exit_code == 124 or exit_code == -9:
        return "timeout"
    if exit_code in (126, 127):
        return "environment_blocked"  # Command not found or not executable

    return "failed"


def parse_junit_xml(xml_path: Path) -> Dict[str, Any]:
    """Parse standard JUnit XML test report generated by pytest, unittest, or CI."""
    if not xml_path.is_file():
        return {}
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()
        summary = {
            "total": 0, "passed": 0, "failed": 0,
            "errors": 0, "skipped": 0, "time_seconds": 0.0,
            "test_cases": []
        }
        # Root can be <testsuites> or single <testsuite>
        suites = root.findall(".//testsuite") if root.tag == "testsuites" else [root]
        for suite in suites:
            summary["total"] += int(suite.attrib.get("tests", 0))
            summary["failed"] += int(suite.attrib.get("failures", 0))
            summary["errors"] += int(suite.attrib.get("errors", 0))
            summary["skipped"] += int(suite.attrib.get("skipped", 0))
            summary["time_seconds"] += float(suite.attrib.get("time", 0.0))

            for tc in suite.findall("testcase"):
                name = tc.attrib.get("name", "")
                classname = tc.attrib.get("classname", "")
                tc_time = float(tc.attrib.get("time", 0.0))
                status = "passed"
                failure_msg = None

                failure_elem = tc.find("failure")
                error_elem = tc.find("error")
                skipped_elem = tc.find("skipped")

                if failure_elem is not None:
                    status = "failed"
                    failure_msg = failure_elem.attrib.get("message") or failure_elem.text
                elif error_elem is not None:
                    status = "error"
                    failure_msg = error_elem.attrib.get("message") or error_elem.text
                elif skipped_elem is not None:
                    status = "skipped"

                summary["test_cases"].append({
                    "name": name,
                    "classname": classname,
                    "time": tc_time,
                    "status": status,
                    "failure_message": (failure_msg or "")[:1000]
                })

        summary["passed"] = max(0, summary["total"] - summary["failed"] - summary["errors"] - summary["skipped"])
        return summary
    except Exception as exc:
        return {"parse_error": str(exc)}


def parse_coverage_json(json_path: Path) -> Dict[str, Any]:
    """Parse standard Coverage.py JSON output."""
    if not json_path.is_file():
        return {}
    try:
        data = json.loads(json_path.read_text(encoding="utf-8"))
        totals = data.get("totals", {})
        return {
            "percent_covered": totals.get("percent_covered", 0.0),
            "covered_lines": totals.get("covered_lines", 0),
            "missing_lines": totals.get("missing_lines", 0),
            "num_statements": totals.get("num_statements", 0),
            "branch_coverage": totals.get("percent_covered_display")
        }
    except Exception as exc:
        return {"parse_error": str(exc)}


class RepoCheckRunner:
    """Run configured checks in a restricted container with a read-only repository."""

    def __init__(self, repo_root: Path, artifact_dir: Optional[Path] = None, timeout_seconds: int = 60):
        self.repo_root = repo_root.resolve()
        self.artifact_dir = (artifact_dir or (self.repo_root / ".root-scout" / "checks")).resolve()
        self.timeout_seconds = timeout_seconds
        self._cache = {}

    def compute_cache_key(self, check_id: str, selector: str, code_sha256: str) -> str:
        h = hashlib.sha256()
        h.update(check_id.encode("utf-8"))
        h.update(selector.encode("utf-8"))
        h.update(code_sha256.encode("utf-8"))
        return h.hexdigest()

    def run_check(
        self,
        check_id: str,
        command: List[str],
        selector: str = "",
        code_sha256: str = "",
        env: Optional[Dict[str, str]] = None,
        use_cache: bool = True
    ) -> Dict[str, Any]:
        """Execute a check in Docker; unavailable Docker never falls back to the host."""
        if not isinstance(command, list) or not command or any(not isinstance(x, str) or not x or "\0" in x for x in command):
            raise ValueError("command must be a nonempty list of argument strings")
        if not isinstance(check_id, str) or not re.fullmatch(r"[A-Za-z0-9_.-]{1,80}", check_id):
            raise ValueError("check_id must be a short filename-safe identifier")
        if env is not None and (not isinstance(env, dict) or any(
                not isinstance(k, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k)
                or not isinstance(v, str) or "\0" in v for k, v in env.items())):
            raise ValueError("env must contain valid environment names and string values")
        if use_cache and code_sha256:
            cache_key = self.compute_cache_key(check_id, selector, code_sha256)
            if cache_key in self._cache:
                cached = dict(self._cache[cache_key])
                cached["from_cache"] = True
                return cached

        name = "root-scout-check-" + uuid.uuid4().hex[:12]
        cid_dir = tempfile.TemporaryDirectory(prefix="root-scout-check-")
        cid_root = Path(cid_dir.name).resolve()
        if cid_root.parent != Path(tempfile.gettempdir()).resolve():
            raise ValueError("container id directory is outside the temporary directory")
        cid_file = cid_root / "container-id"
        container_env = {"PYTHONUNBUFFERED": "1", "PYTHONDONTWRITEBYTECODE": "1", "CI": "1", "HOME": "/tmp"}
        container_env.update(env or {})
        docker = ["docker", "run", "--rm", "--pull=never", "--network=none", "--read-only",
                  "--user", "65534:65534", "--cap-drop=ALL", "--security-opt=no-new-privileges",
                  "--pids-limit=64", "--memory=512m", "--cpus=1", "--ulimit", "fsize=67108864:67108864",
                  "--tmpfs", "/tmp:rw,exec,size=64m", "--name", name, "--cidfile", str(cid_file),
                  "-v", f"{self.repo_root}:/workspace:ro", "-w", "/workspace"]
        for key, value in container_env.items():
            docker.extend(["--env", f"{key}={value}"])
        docker.extend([os.environ.get("ROOT_SCOUT_IMAGE", "root-scout:local"), *command])
        started = time.monotonic()
        timed_out = False
        truncated = {"stdout": False, "stderr": False}
        buffers = {"stdout": bytearray(), "stderr": bytearray()}
        overflow = threading.Event()
        proc = None
        threads = []

        def remove_owned_container():
            try:
                container_id = cid_file.read_text(encoding="ascii").strip()
                if re.fullmatch(r"[0-9a-f]{64}", container_id):
                    subprocess.run(["docker", "rm", "-f", container_id], capture_output=True, timeout=5)
            except (OSError, UnicodeError, subprocess.SubprocessError):
                pass

        def drain(pipe, key, limit):
            try:
                while True:
                    chunk = pipe.read(4096)
                    if not chunk:
                        break
                    remaining = limit - len(buffers[key])
                    buffers[key].extend(chunk[:max(0, remaining)])
                    if len(chunk) > remaining:
                        truncated[key] = True
                        overflow.set()
            finally:
                pipe.close()

        try:
            proc = subprocess.Popen(docker, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            for pipe, key, limit in ((proc.stdout, "stdout", 65536), (proc.stderr, "stderr", 10000)):
                thread = threading.Thread(target=drain, args=(pipe, key, limit), daemon=True)
                thread.start()
                threads.append(thread)
            deadline = started + self.timeout_seconds
            while proc.poll() is None and not overflow.is_set():
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    timed_out = True
                    break
                try:
                    proc.wait(timeout=min(0.1, remaining))
                except subprocess.TimeoutExpired:
                    pass
            if proc.poll() is None:
                remove_owned_container()
                try:
                    proc.kill()
                except OSError:
                    pass
            proc.wait(timeout=5)
            exit_code = proc.returncode
        except (OSError, subprocess.SubprocessError) as exc:
            exit_code = 127
            buffers["stderr"].extend(f"Docker execution failed: {exc}".encode("utf-8", "replace")[:10000])
        finally:
            if proc is not None:
                if proc.poll() is None:
                    try:
                        proc.kill()
                    except OSError:
                        pass
                remove_owned_container()
            for thread in threads:
                thread.join(timeout=5)
            cid_dir.cleanup()

        wall_seconds = round(time.monotonic() - started, 3)
        stdout = bytes(buffers["stdout"]).decode("utf-8", "replace")
        stderr = bytes(buffers["stderr"]).decode("utf-8", "replace")
        tool_name = command[0] if command else "check"
        classification = ("timeout" if timed_out else "output_limit" if any(truncated.values()) else
                          "environment_blocked" if exit_code in (125, 126, 127) else
                          classify_exit(tool_name, exit_code, stderr=stderr))

        record = {
            "check_id": check_id,
            "command": command,
            "selector": selector,
            "exit_code": exit_code,
            "classification": classification,
            "passed": (classification == "passed"),
            "wall_seconds": wall_seconds,
            "stdout_preview": stdout[:2000],
            "stderr_preview": stderr[:1500],
            "stdout_bytes": len(buffers["stdout"]),
            "stderr_bytes": len(buffers["stderr"]),
            "timed_out": timed_out,
            "stdout_truncated": truncated["stdout"],
            "stderr_truncated": truncated["stderr"],
            "execution_environment": "docker_read_only_repository",
            "from_cache": False
        }

        if use_cache and code_sha256:
            cache_key = self.compute_cache_key(check_id, selector, code_sha256)
            self._cache[cache_key] = record

        return record
